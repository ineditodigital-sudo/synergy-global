/**
 * CMS interface texts in Spanish and English.
 * The website content itself is always in English (US market); only the
 * editor's interface changes language.
 */

export function detectLang() {
  try {
    return String(navigator.language || '').toLowerCase().startsWith('es') ? 'es' : 'en';
  } catch {
    return 'en';
  }
}

export function translate(dict, lang, key, params) {
  let s = dict[lang]?.[key] ?? dict.en[key] ?? dict.es[key];
  if (s === undefined) {
    if (import.meta.env?.DEV) console.warn(`[i18n] missing key: ${key}`);
    s = key;
  }
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined && params[k] !== null ? String(params[k]) : m));
  return s;
}

